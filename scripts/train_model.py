"""Build a reproducible labeled demonstration set for a k-NN robot policy.

Run: python3 scripts/train_model.py

Demonstrations are synthetic, generated by a hand-designed *teacher* policy.
At runtime the robot uses the k-NN learned policy, not the teacher rule.
This is supervised imitation of a rule-based controller, not reinforcement
learning or training on data captured from a real/simulated robot.
"""
import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODEL_FILE = ROOT / 'controllers' / 'ai_navigation' / 'training_data.json'


def teacher(fr, fl, bearing):
    """Labels: 0 forward, 1 left, 2 right."""
    if max(fr, fl) >= 0.19:
        if fr > fl + 0.025:
            return 1  # right-hand obstacle -> steer left
        if fl > fr + 0.025:
            return 2  # left-hand obstacle -> steer right
        return 1 if bearing >= 0 else 2
    if bearing > 0.065:
        return 1
    if bearing < -0.065:
        return 2
    return 0


def random_features(rng):
    scenario = rng.random()
    if scenario < 0.42:  # free space (real IR values normally close to 0)
        fr = rng.uniform(0, 0.11)
        fl = rng.uniform(0, 0.11)
    elif scenario < 0.68:  # obstacle in front-right
        fr = rng.uniform(0.2, 1)
        fl = rng.uniform(0, 0.13)
    elif scenario < 0.94:  # obstacle in front-left
        fr = rng.uniform(0, 0.13)
        fl = rng.uniform(0.2, 1)
    else:  # tight confines; both sensors detect obstacles
        fr = rng.uniform(0.18, 1)
        fl = rng.uniform(0.18, 1)
    bearing = rng.uniform(-1, 1)
    return round(fr, 5), round(fl, 5), round(bearing, 5)


def main():
    rng = random.Random(20261020)
    examples = []
    # Dense free-space samples help distinguish forward from tiny turns.
    for bearing in (-0.06, -0.04, -0.02, 0.0, 0.02, 0.04, 0.06):
        for _ in range(50):
            a, b = rng.uniform(0, 0.07), rng.uniform(0, 0.07)
            examples.append([round(a, 5), round(b, 5), bearing, teacher(a, b, bearing)])
    for _ in range(5650):
        a, b, c = random_features(rng)
        examples.append([a, b, c, teacher(a, b, c)])
    rng.shuffle(examples)
    MODEL_FILE.parent.mkdir(parents=True, exist_ok=True)
    with MODEL_FILE.open('w', encoding='utf-8') as f:
        json.dump({
            'algorithm': 'k-nearest neighbors, supervised imitation from synthetic examples',
            'features': ['right_front_proximity', 'left_front_proximity', 'goal_bearing/pi'],
            'labels': ['forward', 'turn_left', 'turn_right'],
            'k': 3,
            'seed': 20261020,
            'examples': examples,
        }, f, separators=(',', ':'))
    print(f'Created {len(examples)} labeled examples -> {MODEL_FILE}')


if __name__ == '__main__':
    main()
